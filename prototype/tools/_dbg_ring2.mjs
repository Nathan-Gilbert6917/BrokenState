import { createWorld, hub, atBase } from "../src/sim/world.js";
import { queueBuild, addBuilding, constructionHour, canBuild } from "../src/sim/buildings.js";
import { ringPlan, ringHalf, yardHalf, wallInfo } from "../src/sim/basemap.js";
const st = createWorld({ seed: 7, factionCount: 4 }); st.started = true;
const h = hub(st);
for (const k of ["scrap", "wood", "buildmat", "parts"]) h.stock[k] = 50000;
for (const s of atBase(st, h.id)) s.role = "build";
const R0 = ringHalf(h), n0 = ringPlan(st, h).pieces.length;
console.log("queue:", queueBuild(st, h, "walls").slice(0, 80));
for (let i = 0; i < 6; i++) h.construction.push({ id: 900000 + i, type: "gen_hut", progress: 0, hours: 14, cost: {}, paid: {} });
const job = h.construction.find((c) => c.type === "walls");
job.paid = { ...job.cost }; job.progress = job.hours - 0.01;
for (let i = 0; i < 3 && h.construction.includes(job); i++) constructionHour(st);
const wi = wallInfo(st, h);
console.log(JSON.stringify({ R0, n0, R: ringHalf(h), C: yardHalf(h), done: !h.construction.includes(job), pieces: h.buildings.filter((b) => /^(wall|gate)/.test(b.type)).length, enclosed: wi.enclosed, planLeft: ringPlan(st, h).pieces.length, again: canBuild(st, h, "walls").kind }));
import { layoutOf, landFor } from "../src/sim/basemap.js";
const lay = layoutOf(st, h).filter((e) => /^(wall|gate)/.test(e.it.type));
console.log("unplaced", lay.filter((e) => !e.at).map((e) => e.it.type).join(","), "placed", lay.filter((e) => e.at).length);
const land = landFor(st, h); console.log("land pieces", land.list.length);
console.log("plan", JSON.stringify(ringPlan(st, h)));
